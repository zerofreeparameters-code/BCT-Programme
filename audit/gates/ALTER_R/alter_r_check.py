class Q2:
    """p + q*sqrt(2), p and q rational. Exact."""
    __slots__ = ("p", "q")
    def __init__(s, p=0, q=0): s.p, s.q = F(p), F(q)
    def _c(s, o): return o if isinstance(o, Q2) else Q2(o, 0)
    def __add__(s, o): o = s._c(o); return Q2(s.p + o.p, s.q + o.q)
    __radd__ = __add__
    def __neg__(s): return Q2(-s.p, -s.q)
    def __sub__(s, o): return s + (-s._c(o))
    def __mul__(s, o):
        o = s._c(o); return Q2(s.p*o.p + 2*s.q*o.q, s.p*o.q + s.q*o.p)
    __rmul__ = __mul__
    def __truediv__(s, o):
        o = s._c(o); n = o.p*o.p - 2*o.q*o.q
        return s * Q2(o.p/n, -o.q/n)
    def __eq__(s, o): o = s._c(o); return s.p == o.p and s.q == o.q
    def __hash__(s): return hash((s.p, s.q))
    def __repr__(s):
        if s.q == 0: return str(s.p)
        if s.p == 0: return f"{s.q}*sqrt2"
        return f"({s.p}+{s.q}*sqrt2)"
SQRT2 = Q2(0, 1)

