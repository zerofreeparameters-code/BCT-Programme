def fr(x): return x if isinstance(x, F) else F(x)
def vec(*a): return tuple(fr(x) for x in a)
def mod1(v): return tuple(x - (x.numerator // x.denominator) for x in v)
def vadd(a, b): return tuple(x + y for x, y in zip(a, b))
def vsub(a, b): return tuple(x - y for x, y in zip(a, b))
def mat(rows): return tuple(tuple(fr(x) for x in r) for r in rows)
def mv(M, v): return tuple(sum(M[i][j]*v[j] for j in range(3)) for i in range(3))
def mm(A, B): return tuple(tuple(sum(A[i][k]*B[k][j] for k in range(3)) for j in range(3)) for i in range(3))
def det(M):
    return (M[0][0]*(M[1][1]*M[2][2]-M[1][2]*M[2][1])
          - M[0][1]*(M[1][0]*M[2][2]-M[1][2]*M[2][0])
          + M[0][2]*(M[1][0]*M[2][1]-M[1][1]*M[2][0]))
def trace(M): return M[0][0]+M[1][1]+M[2][2]
def inv3(M):
    d = det(M)
    c = lambda i, j: (M[(i+1)%3][(j+1)%3]*M[(i+2)%3][(j+2)%3]
                      - M[(i+1)%3][(j+2)%3]*M[(i+2)%3][(j+1)%3])
    return tuple(tuple(c(j, i)/d for j in range(3)) for i in range(3))
I3 = mat([[1,0,0],[0,1,0],[0,0,1]])
MINUS_I3 = mat([[-1,0,0],[0,-1,0],[0,0,-1]])

def closure(gens):
    """Finite matrix group generated by gens."""
    G = {I3}; frontier = [I3]
    while frontier:
        new = []
        for g in frontier:
            for h in gens:
                x = mm(h, g)
                if x not in G:
                    G.add(x); new.append(x)
        frontier = new
    return sorted(G)

# Point groups, as integer matrices acting on fractional coordinates.
C4z = mat([[0,-1,0],[1,0,0],[0,0,1]])
C2x = mat([[1,0,0],[0,-1,0],[0,0,-1]])
D4H = closure([C4z, C2x, MINUS_I3])                     # tetragonal cell, order 16
OH  = closure([C4z, mat([[0,0,1],[1,0,0],[0,1,0]]), MINUS_I3])   # cubic cell, order 48
assert len(D4H) == 16 and len(OH) == 48

def op_type(R):
    """Geometric type of a point operation from (det, trace): basis independent."""
    d, t = det(R), trace(R)
    table = {(1,3):"1", (1,-1):"2", (1,0):"3", (1,1):"4", (1,2):"6",
             (-1,-3):"-1", (-1,1):"m", (-1,0):"-3", (-1,-1):"-4", (-1,-2):"-6"}
    return table[(int(d), int(t))]

def transform_label(lab, R):
    """How a site label transforms under the point part R.
       plain string         : scalar (species / occupancy)
       ('ps', s)            : pseudoscalar (handedness, chirality) -> det(R)*s
       ('ax', (x,y,z))      : axial vector (circulation, spin)     -> det(R)*R v
       ('pv', (x,y,z))      : polar vector                         -> R v
       ('dir', (x,y,z))     : director (headless axis)             -> +-R v, canonical sign
       A tuple label may carry extra trailing fields, kept unchanged."""
    if isinstance(lab, str): return lab
    kind = lab[0]
    if kind == "ps": return ("ps", det(R)*lab[1]) + tuple(lab[2:])
    if kind == "ax": return ("ax", tuple(det(R)*x for x in mv(R, lab[1]))) + tuple(lab[2:])
    if kind == "pv": return ("pv", mv(R, lab[1])) + tuple(lab[2:])
    if kind == "dir":
        w = mv(R, lab[1])
        for x in w:
            if x != 0:
                if x < 0: w = tuple(-y for y in w)
                break
        return ("dir", w) + tuple(lab[2:])
    raise ValueError(kind)

class Structure:
    """Periodic decorated point set in a conventional cell.
       centrings: centring vectors (always including 0); lattice = Z^3 + centrings.
       sites: iterable of (position, label); expanded by centrings, reduced mod 1."""
    def __init__(self, centrings, sites, name=""):
        self.name = name
        self.cent = sorted({mod1(vec(*c)) for c in centrings} | {vec(0,0,0)})
        pts = {}
        for p, lab in sites:
            for c in self.cent:
                q = mod1(vadd(vec(*p), c))
                if q in pts and pts[q] != lab:
                    raise ValueError(f"two labels on one site {q}: {pts[q]} vs {lab}")
                pts[q] = lab
        self.pts = pts
    def canon_t(self, t):
        return min(mod1(vadd(t, c)) for c in self.translation_cosets())
    def maps_to(self, R, t, other=None):
        """Does (R|t) map self onto other (default self), labels included?"""
        tgt = (other or self).pts
        if len(tgt) != len(self.pts): return False
        for p, lab in self.pts.items():
            q = mod1(vadd(mv(R, p), t))
            if tgt.get(q, None) != transform_label(lab, R): return False
        return True
    def translation_cosets(self):
        """The TRUE translation group of this decorated structure, as cosets modulo Z^3:
           the input centrings plus any further pure translation the structure happens to have."""
        if getattr(self, "_tc", None) is None:
            p0, lab0 = next(iter(self.pts.items()))
            tc = set()
            for q, lq in self.pts.items():
                if lq != lab0: continue
                t = mod1(vsub(q, p0))
                if self.maps_to(I3, t): tc.add(t)
            self._tc = tc
        return self._tc
    def lattice_compatible(self, R):
        """A point operation can only belong to the symmetry group if it maps the true translation
           lattice into itself. Without this test a rational (non-integer) matrix -- e.g. a cubic
           3-fold written in the tetragonal frame -- would be 'verified' against one cell only and
           wrongly accepted for a structure whose lattice it does not preserve."""
        tc = self.translation_cosets()
        gens = [vec(1,0,0), vec(0,1,0), vec(0,0,1)] + [t for t in tc if any(x != 0 for x in t)]
        return all(mod1(mv(R, g)) in tc for g in gens)
    def ops_onto(self, pointops, other=None):
        """All (R|t), t modulo the lattice, mapping self onto other (default self)."""
        o = other or self
        p0, lab0 = min(self.pts.items(), key=lambda kv: sum(1 for l in self.pts.values() if l == kv[1]))
        found = set()
        for R in pointops:
            if not self.lattice_compatible(R): continue
            l0 = transform_label(lab0, R); Rp = mv(R, p0)
            for q, lq in o.pts.items():
                if lq != l0: continue
                t = self.canon_t(vsub(q, Rp))
                if (R, t) in found: continue
                if self.maps_to(R, t, o): found.add((R, t))
        return sorted(found)
    def is_lattice_vector(self, v):
        return any(all(x.denominator == 1 for x in vsub(v, c)) for c in self.cent)

def order_of(R):
    n, M = 1, R
    while M != I3: M = mm(M, R); n += 1
    return n

def in_integer_span(gens, target):
    """Exact test: is the rational vector `target` an INTEGER combination of the rational vectors `gens`?
       All vectors are scaled to integers by a common denominator, the generators are brought to row-echelon
       form by unimodular integer row operations (Euclid), and the target is reduced against the pivots.
       No search bound is involved."""
    from math import gcd
    den = 1
    for v in list(gens) + [target]:
        for x in v: den = den * x.denominator // gcd(den, x.denominator)
    rows = [[int(x * den) for x in v] for v in gens if any(x != 0 for x in v)]
    tgt = [int(x * den) for x in target]
    basis = []                                   # echelon rows as (pivot column, row)
    for col in range(3):
        while True:                              # Euclid on column `col` among the remaining rows
            nz = [r for r in rows if r[col] != 0]
            if len(nz) <= 1: break
            nz.sort(key=lambda r: abs(r[col])); p = nz[0]
            for r in nz[1:]:
                q = r[col] // p[col]
                for k in range(3): r[k] -= q * p[k]
        nz = [r for r in rows if r[col] != 0]
        if nz:
            basis.append((col, nz[0])); rows = [r for r in rows if r is not nz[0]]
    for col, p in basis:
        if tgt[col] % p[col] != 0: return False
        q = tgt[col] // p[col]
        tgt = [a - q * b for a, b in zip(tgt, p)]
    return all(x == 0 for x in tgt)

def is_nonsymmorphic_op(S, R, t):
    """True iff (R|t+l) is a screw/glide for EVERY lattice vector l of the structure's true lattice, i.e. the
       operation has an intrinsic fractional translation that no choice of lattice representative removes.
       With P = (1/n) sum_k R^k the projector onto the R-invariant subspace, (R|t+l) has a fixed point iff
       P(t+l) = 0. So the operation is point-type for some representative iff -P t lies in the integer span of
       {P g : g a generator of the lattice}; this is decided exactly by in_integer_span (no bounded search)."""
    n = order_of(R)
    acc, M = [[F(0)]*3 for _ in range(3)], I3
    for _ in range(n):
        acc = [[acc[i][j] + M[i][j] for j in range(3)] for i in range(3)]
        M = mm(M, R)
    P = tuple(tuple(x / n for x in row) for row in acc)
    gens = [vec(1,0,0), vec(0,1,0), vec(0,0,1)] + [c for c in S.translation_cosets() if any(x != 0 for x in c)]
    return not in_integer_span([mv(P, g) for g in gens], tuple(-x for x in mv(P, t)))

def fmt_v(v): return "(" + ",".join(str(x) for x in v) + ")"
def fmt_op(S, R, t):
    ty = op_type(R)
    tag = ""
    if ty not in ("1", "-1"):
        tag = " [screw/glide]" if is_nonsymmorphic_op(S, R, t) else ""
    elif ty == "1" and not all(x == 0 for x in t):
        tag = " [pure translation]"
    rows = ";".join(" ".join(f"{int(x):2d}" if x.denominator == 1 else str(x) for x in r) for r in R)
    return f"{ty:>3} | t={fmt_v(t)}{tag}   R=[{rows}]"

def triplet(R, t):
    """Coordinate-triplet form of (R|t), as in International Tables: e.g. -y+1/2,x+1/2,z+1/2."""
    out = []
    for i in range(3):
        term = ""
        for j, ax in enumerate("xyz"):
            c = R[i][j]
            if c == 0: continue
            mag = "" if abs(c) == 1 else (str(abs(c)) + "*")
            term += ("-" if c < 0 else ("+" if term else "")) + mag + ax
        if t[i] != 0: term += ("+" if t[i] > 0 else "") + str(t[i])
        out.append(term or "0")
    return ",".join(out)

