def rutile_sites(u):
    metal_A = [(vec(0,0,0), "M")]
    metal_B = [(vec(F(1,2),F(1,2),F(1,2)), "M")]
    oxy = [(vec(u,u,0), "X"), (vec(-u,-u,0), "X"),
           (vec(F(1,2)+u, F(1,2)-u, F(1,2)), "X"), (vec(F(1,2)-u, F(1,2)+u, F(1,2)), "X")]
    return metal_A, metal_B, oxy

def rutile_tests(u, verbose=False):
    A, B, X = rutile_sites(u)
    S = Structure([], A + B + X)
    body = vec(F(1,2),F(1,2),F(1,2))
    Xonly = Structure([], X)
    trans_maps_X = Xonly.maps_to(I3, body)
    screw_maps_X = Xonly.maps_to(C4z, body)
    screw_maps_all = S.maps_to(C4z, body)
    return trans_maps_X, screw_maps_X, screw_maps_all

class Lin:
    """alpha + beta*u with u a free symbol: exact generic-u arithmetic mod 1."""
    def __init__(s, al, be): s.al, s.be = F(al), int(be)
    def __add__(s, o): return Lin(s.al + o.al, s.be + o.be)
    def __neg__(s): return Lin(-s.al, -s.be)
    def key(s): return (s.al - (s.al.numerator // s.al.denominator), s.be)

