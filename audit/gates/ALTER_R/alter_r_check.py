# CROSSCHECK (non-gating)  compare every operation set found above with the
# tabulated general positions of the named space group, taken from the spglib
# database (Hall-symbol tables, which reproduce International Tables Vol. A).
# Optional: needs `pip install spglib`. It is reported separately and is NOT
# counted among the exact-arithmetic assertions, because the database stores
# its translations as floats (0.25, 0.5 ...; converted here to rationals).
# --------------------------------------------------------------------------
def crosscheck():
    section("CROSSCHECK (non-gating)  operation sets vs tabulated space-group operations (spglib database)")
    try:
        import spglib
    except Exception as ex:                                   # pragma: no cover
        print(f"  spglib not available ({ex.__class__.__name__}); cross-check skipped. The exact checks above do not depend on it.")
        return
    def db(hall):
        d = spglib.get_symmetry_from_database(hall)
        return [(mat([[int(x) for x in r] for r in R]), tuple(F(float(x)).limit_denominator(24) for x in t))
                for R, t in zip(d["rotations"], d["translations"])]
    def canon(t, cosets): return min(mod1(vadd(t, c)) for c in cosets)
    FCC_COS = [vec(0,0,0)] + FCC
    def compare(label, hall, sites, cent, pointops, cubic=False):
        S = Structure(cent, sites); mine = S.ops_onto(pointops)
        if cubic:      # my structures live in the tetragonal frame; the table is in the cubic frame
            mine_c = {(mm(M_T2C, mm(R, M_C2T)), canon(mv(M_T2C, t), FCC_COS)) for R, t in mine}
            tab = {(R, canon(t, FCC_COS)) for R, t in db(hall)}
        else:
            mine_c = {(R, S.canon_t(t)) for R, t in mine}
            tab = {(R, S.canon_t(t)) for R, t in db(hall)}
        ty = spglib.get_spacegroup_type(hall)
        ok = mine_c == tab
        print(f"  {'MATCH   ' if ok else 'MISMATCH'}  {label}: {len(mine_c)} ops found vs {len(tab)} tabulated for "
              f"{ty.international_full.strip()} (No. {ty.number}{', origin choice ' + ty.choice if ty.choice else ''}, Hall {hall})")
        return ok
    u = F(61, 200); A, B, X = rutile_sites(u)
    sph = [(SPH_A, "S")]
    R_, L_ = ("ps", F(1)), ("ps", F(-1))
    res = [
      compare("control MnF2 (rutile)", 419, A + B + X, [], D4H),
      compare("NM-1(i)/NM-5 bare BCT, generic c/a", 424, sph, BCT, D4H),
      compare("NM-1(i) bare BCT at c/a = sqrt2", 523, sph, BCT, OH_T, cubic=True),
      compare("NM-2 handedness staggered (pseudoscalar), generic c/a", 404, [(SPH_A, R_), (SPH_B, L_)], [], D4H),
      compare("NM-2 handedness staggered (pseudoscalar), c/a = sqrt2", 404, [(SPH_A, R_), (SPH_B, L_)], [], OH_T),
      compare("NM-2 alt two scalar labels", 400, [(SPH_A, "R"), (SPH_B, "L")], [], OH_T),
      compare("NM-3 c-director on oct voids, c/a = sqrt2", 424, sph + [(OCT_T[0], ("dir", vec(0,0,1)))], BCT, OH_T),
      compare("NM-4 scalar labels, c/a = sqrt2", 523, sph + [(OCT_T[0], "X"), (TET1[0], "Y"), (TET2[0], "Y")], BCT, OH_T, cubic=True),
      compare("NM-4 pseudoscalar handedness, c/a = sqrt2", 505,
              sph + [(OCT_T[0], L_), (TET1[0], R_), (TET2[0], R_)], BCT, OH_T, cubic=True),
      compare("NM-4 pseudoscalar handedness, generic c/a", 374,
              sph + [(OCT_T[0], L_), (TET1[0], R_), (TET2[0], R_)], BCT, D4H),
      compare("NM-5 distinct tet labels, generic c/a", 396, sph + [(TET1[0], "Tu"), (TET2[0], "Td")], BCT, D4H),
      compare("NM-5 distinct tet labels, c/a = sqrt2", 512, sph + [(TET1[0], "Tu"), (TET2[0], "Td")], BCT, OH_T, cubic=True),
    ]
    print(f"  cross-check: {sum(res)} / {len(res)} operation sets identical to the tabulated group")
    # independent structure-level identification for the scalar-labelled structures (floating point inside spglib)
    try:
        import numpy as np
        def ident(label, sites, cent, c_over_a):
            S = Structure(cent, sites); labs = sorted({str(l) for l in S.pts.values()})
            pos = [[float(x) for x in p] for p in S.pts]; num = [labs.index(str(l)) + 1 for l in S.pts.values()]
            cell = (np.diag([1.0, 1.0, c_over_a]), pos, num)
            print(f"  spglib.get_spacegroup  {label:58s} -> {spglib.get_spacegroup(cell, symprec=1e-6)}")
        r2 = 2 ** 0.5
        ident("control MnF2 (c/a = 0.68 as in the real crystal)", A + B + X, [], 0.68)
        ident("bare BCT, c/a = 1.2 (generic)", sph, BCT, 1.2)
        ident("bare BCT, c/a = sqrt2", sph, BCT, r2)
        ident("NM-2 alt two scalar labels, c/a = sqrt2", [(SPH_A, 'R'), (SPH_B, 'L')], [], r2)
        ident("NM-4 scalar labels, c/a = sqrt2", sph + [(OCT_T[0], 'X'), (TET1[0], 'Y'), (TET2[0], 'Y')], BCT, r2)
        ident("NM-5 distinct tet labels, c/a = 1.2", sph + [(TET1[0], 'Tu'), (TET2[0], 'Td')], BCT, 1.2)
        ident("NM-5 distinct tet labels, c/a = sqrt2", sph + [(TET1[0], 'Tu'), (TET2[0], 'Td')], BCT, r2)
        ident("NM-3 c-axis marked on oct voids by two satellites, sqrt2",
              sph + [(vec(H, H, F(1,10)), 'm'), (vec(H, H, F(-1,10)), 'm')], BCT, r2)
    except Exception as ex:                                   # pragma: no cover
        print(f"  structure-level identification skipped ({ex.__class__.__name__}: {ex})")

