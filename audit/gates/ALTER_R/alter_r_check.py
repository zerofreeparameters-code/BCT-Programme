def describe(name, cent, sites, pointops, list_ops=True):
    """Full surviving operation set (printed as coordinate triplets) + the fingerprint used to name the space group.
       Tetragonal groups are printed in the tetragonal frame; cubic groups are converted exactly to the cubic frame
       (x,y,z)_c = M (x,y,z)_t and reduced modulo the face-centring translations, so that they can be read against
       International Tables directly."""
    g = full_group(name, cent, sites, pointops, list_ops=False)
    S = g["S"]; ops = g["ops"]
    lattice = "I" if BODY in S.translation_cosets() else "P"
    assert len(S.translation_cosets()) == (2 if lattice == "I" else 1)
    def status(R):
        hit = [(r, t) for r, t in ops if r == R]
        if not hit: return "absent"
        return "glide/screw" if is_nonsymmorphic_op(S, *hit[0]) else "point-type"
    fp = dict(lattice=lattice, pg=g["pg"], n=len(ops), nonsym=g["nonsym"],
              four=status(C4z), two_a=status(C2x), m_c=status(MZ), m_a=status(MX), m_d=status(MD),
              inv="present" if any(R == MINUS_I3 for R, _ in ops) else "absent",
              body_translation=S.maps_to(I3, BODY))
    cubic = g["pg"].split()[0] in ("Oh", "O", "Td", "Th", "T")
    if cubic:
        cos = [vec(0,0,0)] + FCC
        trip = sorted({triplet(mm(M_T2C, mm(R, M_C2T)), min(mod1(vadd(mv(M_T2C, t), c)) for c in cos)) for R, t in ops})
        frame = "cubic frame, modulo F-centring (0,0,0; 0,1/2,1/2; 1/2,0,1/2; 1/2,1/2,0)"
    else:
        trip = sorted(triplet(R, t) for R, t in ops)
        frame = "tetragonal frame" + (", modulo I-centring (0,0,0; 1/2,1/2,1/2)" if lattice == "I" else ", primitive lattice")
    OPSETS[name] = dict(frame=frame, ops=trip, fingerprint={k: str(v) for k, v in fp.items()})
    if list_ops:
        print(f"    surviving operations ({len(trip)}; {frame}):")
        for k in range(0, len(trip), 4):
            print("      " + "   ".join(f"{x:24s}" for x in trip[k:k+4]).rstrip())
    print(f"    fingerprint: lattice {fp['lattice']} (tetragonal description); point group {fp['pg']}; {fp['n']} ops; "
          f"screw/glide ops {fp['nonsym']}; 4-fold about c {fp['four']}; 2 along a {fp['two_a']}; plane normal to c {fp['m_c']}; "
          f"normal to a {fp['m_a']}; normal to [110] {fp['m_d']}; inversion {fp['inv']}")
    print(f"    corner -> body-centre by the PURE translation (1/2,1/2,1/2) is a symmetry of this decorated structure: "
          f"{'YES' if fp['body_translation'] else 'NO'}")
    return g, fp

