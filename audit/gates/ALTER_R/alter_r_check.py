def point_group(ops):
    Rs = sorted({R for R, _ in ops}); sig = {}
    for R in Rs: sig[op_type(R)] = sig.get(op_type(R), 0) + 1
    for name, s in PG_SIGNATURES.items():
        if s == sig: return name, len(Rs)
    return f"unlisted {sig}", len(Rs)

def translations(ops):
    """Pure translations in the op list (R = identity), modulo the input lattice."""
    return sorted(t for R, t in ops if R == I3)

def exchange_analysis(name, cent, host_sites, A_sites, B_sites, pointops, verbose=True):
    """The altermagnet test, stated crystallographically.
       Build X_A = host + A marked 'S1' + B marked 'S2' (sublattices distinguishable)
       and X_B = host + A marked 'S2' + B marked 'S1' (sublattices exchanged).
       Operations mapping X_A -> X_A keep each sublattice; X_A -> X_B exchange them.
       Site labels given by the corpus (orientation, handedness...) are carried in
       the label tuple and transform properly under the operation.
       (a) exchanged by a pure lattice translation?   -> degenerate
       (b) exchanged by inversion about some point?    -> degenerate
       (c) exchanged ONLY by rotations / rotoinversions (with or without fractional
           translation), none of type (a) or (b)       -> altermagnetic-allowed."""
    def mark(sites, m):
        out = []
        for p, lab in sites:
            out.append((p, (lab + (m,)) if isinstance(lab, tuple) else f"{lab}#{m}"))
        return out
    XA = Structure(cent, list(host_sites) + mark(A_sites, "S1") + mark(B_sites, "S2"), name)
    XB = Structure(cent, list(host_sites) + mark(A_sites, "S2") + mark(B_sites, "S1"), name)
    keep = XA.ops_onto(pointops)
    swap = XA.ops_onto(pointops, XB)
    a = [(R, t) for R, t in swap if R == I3]
    b = [(R, t) for R, t in swap if R == MINUS_I3]
    c = [(R, t) for R, t in swap if R not in (I3, MINUS_I3)]
    verdict = ("NO EXCHANGE SYMMETRY (sublattices inequivalent: ferri-type, not compensated by symmetry)"
               if not swap else
               "DEGENERATE (translation)" if a else
               "DEGENERATE (inversion)" if b else
               "ALTERMAGNETIC-ALLOWED (rotation/screw/glide only)")
    if verbose:
        print(f"  [{name}]")
        print(f"    sublattice-preserving ops: {len(keep)}   sublattice-exchanging ops: {len(swap)}")
        print(f"    (a) exchanged by pure lattice translation : {'YES ' + fmt_v(a[0][1]) if a else 'NO'}")
        print(f"    (b) exchanged by inversion about a point  : {'YES, centre at ' + fmt_v(tuple(x/2 for x in b[0][1])) if b else 'NO'}")
        kinds = {}
        for R, t in c:
            k = op_type(R) + (" screw/glide" if is_nonsymmorphic_op(XA, R, t) else " point-type")
            kinds[k] = kinds.get(k, 0) + 1
        print(f"    (c) exchanged by rotation/rotoinversion   : {len(c)} ops {kinds if c else ''}".rstrip())
        print(f"    => {verdict}")
    return dict(keep=keep, swap=swap, a=a, b=b, c=c, verdict=verdict, XA=XA)

def full_group(name, cent, sites, pointops, verbose=True, list_ops=False):
    S = Structure(cent, sites, name)
    ops = S.ops_onto(pointops)
    pg, npg = point_group(ops)
    tr = [t for t in S.translation_cosets() if any(x != 0 for x in t) and t not in S.cent]
    nonsym = sum(1 for R, t in ops if R not in (I3,) and op_type(R) != "-1" and is_nonsymmorphic_op(S, R, t))
    if verbose:
        print(f"  [{name}] ops per input-lattice cell: {len(ops)}; point group {pg} (order {npg}); "
              f"extra pure translations beyond input lattice: {len(tr)} {[fmt_v(t) for t in tr]}; "
              f"ops that are screw/glide for every lattice representative: {nonsym}")
        if list_ops:
            for R, t in ops: print("      " + fmt_op(S, R, t))
    return dict(S=S, ops=ops, pg=pg, extra_tr=tr, nonsym=nonsym)

